import { fmtDate, money, rateLabel, upiUri } from '../lib/format.js';
import { QR } from './ui.jsx';

const STATES = { '24': 'Gujarat', '27': 'Maharashtra' };

/**
 * Print-ready A4 Tax Invoice / Bill of Supply / Invoice. Kept in English on purpose (statutory document).
 * Works for saved invoices (d = API detail) and live previews (same shape).
 */
export default function InvoiceDocument({ d, states }) {
  const b = d.business, c = d.customer, inv = d.invoice;
  const stateName = (code) => (states && states[code]) || STATES[code] || code;
  const tax = inv.docType === 'TAX_INVOICE';
  const intra = d.intraState;
  const owed = d.summary ? d.summary.outstandingPaise || inv.totalPaise : inv.totalPaise;
  return (
    <article className="a4 shadow" aria-label={d.docTitle}>
      <header className="flex justify-between items-start gap-4 border-b-2 border-black pb-2">
        <div>
          {b.logoDataUrl && <img src={b.logoDataUrl} alt="" className="h-12 mb-1" />}
          <div className="text-xl font-bold">{b.name}</div>
          <div>{b.address}</div>
          {b.gstin && <div>GSTIN: <strong>{b.gstin}</strong></div>}
          <div>State: {stateName(b.stateCode)} ({b.stateCode})</div>
          {b.phone && <div>Phone: {b.phone} · {b.email}</div>}
        </div>
        <div className="text-right">
          <div className="text-2xl font-bold uppercase">{d.docTitle}</div>
          {inv.docType === 'BILL_OF_SUPPLY' && <div className="font-semibold">Composition taxable person, not eligible to collect tax on supplies</div>}
          <div>Invoice no.: <strong>{inv.invoiceNumber || 'DRAFT'}</strong></div>
          <div>Invoice date: {fmtDate(inv.invoiceDate)}</div>
          <div>Due date: {fmtDate(inv.dueDate)}</div>
        </div>
      </header>
      {d.eInvoiceRequired && <p className="border p-1 mt-2 text-sm">Turnover above ₹5 crore: e-invoice (IRN) required from the government portal. Not generated by this app.</p>}
      <section className="grid grid-cols-2 gap-4 mt-3">
        <div>
          <div className="font-bold">Bill to</div>
          <div className="font-semibold">{c.name}</div>
          <div>{c.address}</div>
          {c.gstin ? <div>GSTIN: {c.gstin}</div> : <div>Unregistered</div>}
          <div>State: {stateName(c.stateCode)} ({c.stateCode})</div>
        </div>
        <div>
          <div>Place of supply: <strong>{d.placeOfSupplyName || stateName(inv.placeOfSupply)} ({inv.placeOfSupply})</strong></div>
          {tax && <div>Tax payable on reverse charge: <strong>{inv.reverseCharge ? 'Yes' : 'No'}</strong></div>}
          {inv.deliveryAddress && <div><span className="font-bold">Delivery address:</span> {inv.deliveryAddress}</div>}
        </div>
      </section>
      <table className="mt-3 text-sm">
        <thead>
          <tr>
            <th>#</th><th>Description</th><th>HSN/SAC</th><th>Qty</th><th>Rate</th><th>Discount</th><th>Taxable value</th>
            {tax && (intra ? <><th>CGST</th><th>SGST</th></> : <th>IGST</th>)}
            <th>Total</th>
          </tr>
        </thead>
        <tbody>
          {d.lines.map((l, i) => (
            <tr key={i}>
              <td>{i + 1}</td><td>{l.description}</td><td>{l.hsnSac}</td><td className="text-right">{Number(l.quantity)} {l.unit}</td>
              <td className="text-right">{money(l.ratePaise)}</td><td className="text-right">{l.discountPaise ? money(l.discountPaise) : '-'}</td>
              <td className="text-right">{money(l.taxablePaise)}</td>
              {tax && (intra
                ? <><td className="text-right">{rateLabel(l.gstRateBp / 2)}<br />{money(l.cgstPaise)}</td><td className="text-right">{rateLabel(l.gstRateBp / 2)}<br />{money(l.sgstPaise)}</td></>
                : <td className="text-right">{rateLabel(l.gstRateBp)}<br />{money(l.igstPaise)}</td>)}
              <td className="text-right">{money(l.totalPaise)}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <section className="flex justify-between gap-4 mt-3">
        <div className="text-sm">
          <div className="font-bold">Amount in words</div>
          <div>{d.amountInWords}</div>
          <div className="mt-3 font-bold">Pay to</div>
          <div>{b.bankName} · A/c {b.accountName} · {b.accountNumber} · IFSC {b.ifsc}</div>
          {b.upiId && owed > 0 && (
            <div className="flex items-center gap-2 mt-2">
              <QR text={upiUri({ upiId: b.upiId, name: b.name, amountPaise: owed, note: inv.invoiceNumber || 'DRAFT' })} size={110} label="UPI QR code to pay this invoice" />
              <div>UPI: {b.upiId}<br />Scan to pay {money(owed)}</div>
            </div>
          )}
        </div>
        <table className="w-auto text-sm" style={{ width: 'auto', minWidth: '45%' }}>
          <tbody>
            <tr><td>Taxable value</td><td className="text-right">{money(inv.taxablePaise)}</td></tr>
            {tax && intra && <><tr><td>CGST</td><td className="text-right">{money(inv.cgstPaise)}</td></tr><tr><td>SGST</td><td className="text-right">{money(inv.sgstPaise)}</td></tr></>}
            {tax && !intra && <tr><td>IGST</td><td className="text-right">{money(inv.igstPaise)}</td></tr>}
            <tr><td>Round off</td><td className="text-right">{money(inv.roundOffPaise)}</td></tr>
            <tr><td className="font-bold">Total</td><td className="text-right font-bold">{money(inv.totalPaise)}</td></tr>
          </tbody>
        </table>
      </section>
      <footer className="flex justify-between items-end mt-10 text-sm">
        <div>{inv.notes}</div>
        <div className="text-center"><div className="mb-10">For {b.name}</div><div className="border-t border-black pt-1 px-6">Authorised signatory</div></div>
      </footer>
    </article>
  );
}
